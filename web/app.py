@app.route("/listing/<slug>")
def listing(slug):
    d = get_db()
    row = d.execute(
        "SELECT * FROM listings WHERE slug = ?", (slug,)).fetchone()
    if not row:
        abort(404)
    nearby = d.execute(
        "SELECT * FROM listings WHERE city = ? AND state = ? AND slug != ? "
        "ORDER BY reviews DESC LIMIT 6",
        (row["city"], row["state"], slug)).fetchall()
    # other dentist specialties available in the same city (internal linking)
    other_specialties = d.execute(
        "SELECT category, COUNT(*) n FROM listings WHERE city = ? AND state = ? "
        "AND category IS NOT NULL AND category != ? GROUP BY category "
        "ORDER BY n DESC", (row["city"], row["state"], row["category"])).fetchall()
    copy = content_for(f"listing:{slug}")
    specialty = SPECIALTY_INFO.get(row["category"])

    # Data-driven FAQ (unique per listing, answered from real data) so every
    # page has genuine Q&A content rather than one boilerplate sentence.
    name, city, st = row["name"], row["city"], row["state"]
    faq = []
    if row["phone"]:
        faq.append({"q": f"How do I contact {name}?",
                    "a": f"You can reach {name} by phone at {row['phone']}. "
                         f"The practice is located in {city}, {st}"
                         + (f" at {row['address']}." if row["address"] else ".")})
    if row["address"]:
        faq.append({"q": f"Where is {name} located?",
                    "a": f"{name} is located at {row['address']}. You can get "
                         f"driving directions from the map on this page."})
    faq.append({"q": f"What type of dentist is {name}?",
                "a": f"{name} is listed as a {row['category']} serving patients "
                     f"in {city}, {st}"
                     + (f". {specialty}" if specialty else ".")})

    last_updated = (row["scraped_at"] or "")[:10]
    return render_template("listing.html", l=row, nearby=nearby, copy=copy,
                           specialty=specialty, faq=faq,
                           other_specialties=other_specialties,
                           last_updated=last_updated, indexable=is_indexable(row))


PER_PAGE = 24


def _page():
    try:
        return max(1, int(request.args.get("page", 1)))
    except ValueError:
        return 1


def _pageinfo(page, total):
    pages = max(1, (total + PER_PAGE - 1) // PER_PAGE)
    return {"page": page, "pages": pages,
            "has_prev": page > 1, "has_next": page < pages}


@app.route("/category/<slug>")
def category(slug):
    d = get_db()
    cats = {slugify(r["category"]): r["category"] for r in d.execute(
        "SELECT DISTINCT category FROM listings WHERE category IS NOT NULL")}
    name = cats.get(slug)
    if not name:
        abort(404)
    page = _page()
    total = d.execute("SELECT COUNT(*) FROM listings WHERE category = ?",
                      (name,)).fetchone()[0]
    rows = d.execute(
        "SELECT * FROM listings WHERE category = ? ORDER BY reviews DESC "
        "LIMIT ? OFFSET ?", (name, PER_PAGE, (page - 1) * PER_PAGE)).fetchall()
    copy = content_for(f"category:{slug}")
    stats = d.execute(
        "SELECT ROUND(AVG(rating),1) avg, COUNT(DISTINCT city||state) cities, "
        "SUM(reviews) revs FROM listings WHERE category = ? AND rating IS NOT NULL",
        (name,)).fetchone()
    top_cities = d.execute(
        "SELECT city, state, COUNT(*) n FROM listings WHERE category = ? "
        "GROUP BY city, state ORDER BY n DESC LIMIT 5", (name,)).fetchall()
    facts = {"avg": stats["avg"], "cities": stats["cities"],
             "reviews": stats["revs"] or 0, "top_cities": top_cities}
    md = meta_desc(
        copy["intro"] if copy else None,
        f"Compare {total:,} top-rated {name.lower()} practices near you. Verified "
        f"reviews, ratings and locations — find and call the right dentist "
        f"today.")
    return render_template("category.html", name=name, slug=slug, rows=rows,
                           total=total, copy=copy, pg=_pageinfo(page, total),
                           facts=facts, meta_description=md,
                           base_url=f"/category/{slug}")


@app.route("/<state>/<cityslug>")
def city(state, cityslug):
    state = state.upper()
    d = get_db()
    # match by slug of city (filter in Python since slugify isn't in SQL)
    allrows = d.execute(
        "SELECT * FROM listings WHERE state = ? ORDER BY reviews DESC",
        (state,)).fetchall()
    rows = [r for r in allrows if slugify(r["city"]) == cityslug]
    if not rows:
        abort(404)
    cname = rows[0]["city"]
    page = _page()
    total = len(rows)
    paged = rows[(page - 1) * PER_PAGE: page * PER_PAGE]
    copy = content_for(f"city:{cityslug}-{state.lower()}")
    rated = [r["rating"] for r in rows if r["rating"] is not None]
    # specialty breakdown with per-specialty average rating (unique per city)
    spec = {}
    for r in rows:
        if r["category"]:
            v = spec.setdefault(r["category"], {"n": 0, "sum": 0.0, "rated": 0})
            v["n"] += 1
            if r["rating"] is not None:
                v["sum"] += r["rating"]; v["rated"] += 1
    specialty_breakdown = sorted(
        [{"cat": k, "n": v["n"],
          "avg": round(v["sum"] / v["rated"], 1) if v["rated"] else None}
         for k, v in spec.items()], key=lambda x: -x["n"])
    # group by ZIP code parsed from the address (unique "areas" data)
    zc = {}
    for r in rows:
        if r["address"]:
            m = re.search(r"\b(\d{5})(?:-\d{4})?\b", r["address"])
            if m:
                zc[m.group(1)] = zc.get(m.group(1), 0) + 1
    areas = sorted(zc.items(), key=lambda x: -x[1])[:12]
    last_updated = max((r["scraped_at"] or "" for r in rows), default="")[:10]
    facts = {"avg": round(sum(rated) / len(rated), 1) if rated else None,
             "reviews": sum(r["reviews"] or 0 for r in rows),
             "top": rows[0],
             "services": [(s["cat"], s["n"]) for s in specialty_breakdown]}
    md = meta_desc(
        copy["intro"] if copy else None,
        f"Compare {total} dentists in {cname}, {state} by specialty, patient "
        f"rating and location. See reviews and phone numbers, then call a local "
        f"dentist directly.")
    return render_template("city.html", city=cname, state=state, rows=paged,
                           total=total, copy=copy, pg=_pageinfo(page, total),
                           facts=facts, meta_description=md,
                           specialty_breakdown=specialty_breakdown, areas=areas,
                           last_updated=last_updated,
                           base_url=f"/{state.lower()}/{cityslug}")


